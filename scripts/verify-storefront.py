"""Browser regression checks for the storefront. Never submits an order.
Requires the Python Playwright package and a running local Next.js server.
Run: python scripts/verify-storefront.py --base-url http://localhost:3000
"""
import argparse,json,sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
sys.stdout.reconfigure(encoding="utf-8")
parser=argparse.ArgumentParser()
parser.add_argument("--base-url",default="http://localhost:3000")
parser.add_argument("--output",default=".gstack/storefront-qa")
args=parser.parse_args()
base=args.base_url.rstrip("/")
out=Path(args.output)
out.mkdir(parents=True,exist_ok=True)
results=[]
def passed(name):
 results.append(name); print("PASS",name,flush=True)
with sync_playwright() as p:
 b=p.chromium.launch(headless=True)
 context=b.new_context(viewport={"width":1440,"height":1000},reduced_motion="reduce")
 page=context.new_page(); errors=[]
 # Keep storefront regressions independent of analytics and avoid analytics writes.
 page.route("**/api/etkinlik",lambda route:route.fulfill(status=204))
 page.on("pageerror",lambda e:errors.append(str(e)))
 page.goto(base,wait_until="networkidle",timeout=60000)
 expect(page.locator(".store-product")).to_have_count(8)
 expect(page.locator("main h1")).to_have_text("Eminönü’nde akvaryum ve balık mağazanız")
 passed("Home renders live categories and 8 live products")
 page.screenshot(path=str(out/"home-desktop.png"),full_page=True)
 for width in [320,390,768,1024,1280,1440]:
  page.set_viewport_size({"width":width,"height":900})
  assert page.evaluate("document.documentElement.scrollWidth <= innerWidth"),f"Overflow {width}"
 passed("Home fits 320, 390, 768, 1024, 1280 and 1440px")
 page.set_viewport_size({"width":390,"height":844})
 page.screenshot(path=str(out/"home-mobile.png"),full_page=True)
 page.set_viewport_size({"width":1440,"height":1000})
 first=page.locator(".store-product").first
 product_url=first.locator("a").first.get_attribute("href")
 first.locator(".store-quick-trigger").click()
 quick=page.locator("dialog.store-dialog[open]")
 expect(quick).to_be_visible()
 page.keyboard.press("Shift+Tab")
 assert page.evaluate("document.querySelector('dialog[open]').contains(document.activeElement)")
 page.keyboard.press("Escape")
 expect(quick).to_have_count(0)
 passed("Quick view opens, traps focus, closes with Escape")
 first.locator(".store-quick-trigger").click()
 page.locator("dialog.store-dialog[open] .store-add").click()
 cart=page.locator("dialog.store-cart[open]")
 expect(cart).to_be_visible()
 expect(page.locator("dialog.store-dialog[open]")).to_have_count(0)
 expect(cart.locator(".store-cart-item")).to_have_count(1)
 plus=cart.get_by_role("button",name="adedini artır",exact=False)
 # Prepare the boundary in a second tab; verifies cross-tab persistence too.
 other=context.new_page()
 other.goto(base,wait_until="networkidle")
 other.evaluate("""() => { const items=JSON.parse(localStorage.getItem('ga_cart')); items[0].qty=Math.max(1,items[0].maxStock-1); localStorage.setItem('ga_cart',JSON.stringify(items)); }""")
 other.close()
 for i in range(10):
  if plus.is_disabled():break
  plus.click()
 expect(plus).to_be_disabled()
 quantity=int(cart.locator(".store-quantity span").inner_text())
 cart.screenshot(path=str(out/"cart.png"))
 page.keyboard.press("Escape")
 page.reload(wait_until="networkidle")
 page.locator(".store-cart-button").click()
 expect(page.locator("dialog.store-cart[open] .store-quantity span")).to_have_text(str(quantity))
 passed("Quick add opens cart, respects stock limit and persists after reload")
 page.locator("dialog.store-cart[open] a[href='/sepet']").click()
 page.wait_for_url("**/sepet",timeout=60000)
 page.wait_for_load_state("networkidle")
 expect(page.locator(".store-checkout-panel")).to_be_visible()
 page.screenshot(path=str(out/"checkout-desktop.png"),full_page=True)
 page.set_viewport_size({"width":390,"height":844})
 assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
 page.screenshot(path=str(out/"checkout-mobile.png"),full_page=True)
 passed("Checkout receives cart and fits mobile")
 page.get_by_role("button",name="Teslimat bilgilerine geç").click()
 page.get_by_role("button",name="Ödemeye Geç",exact=False).click()
 expect(page.locator("#checkout-customer_name")).to_have_attribute("aria-invalid","true")
 expect(page.locator("#checkout-error-customer_name")).to_be_visible()
 for field,value in {"customer_name":"Test Kullanıcı","customer_phone":"05550000000","address":"Test adresi, sokak 1","city":"İstanbul","customer_email":"ux-test@example.invalid"}.items():
  page.locator("#checkout-"+field).fill(value)
 page.get_by_role("button",name="Ödemeye Geç",exact=False).click()
 expect(page.locator(".store-checkout-panel h2")).to_have_text("Ödeme")
 assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
 page.screenshot(path=str(out/"checkout-payment-mobile.png"),full_page=True)
 passed("Checkout validates required fields and advances to payment without submitting an order")
 page.set_viewport_size({"width":1440,"height":1000})
 page.goto(base+product_url,wait_until="networkidle",timeout=60000)
 expect(page.locator(".store-product-detail h1")).to_be_visible()
 page.screenshot(path=str(out/"product-desktop.png"),full_page=True)
 page.set_viewport_size({"width":390,"height":844})
 assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
 page.screenshot(path=str(out/"product-mobile.png"),full_page=True)
 passed("Product detail loads from live catalog and fits mobile")
 page.set_viewport_size({"width":1440,"height":1000})
 page.goto(base+"/urunler?grup=filtreler&stok=1&sirala=price_asc",wait_until="networkidle",timeout=60000)
 expect(page.locator("main h1:visible")).to_contain_text("Filtreler")
 assert page.locator(".store-product").count()>0
 assert page.locator(".store-stock-out").count()==0
 prices=page.locator(".store-product .store-price").all_text_contents()
 vals=[float(''.join(c for c in price if c.isdigit() or c in ',.').replace('.','').replace(',','.')) for price in prices]
 assert vals==sorted(vals)
 page.screenshot(path=str(out/"catalog-desktop.png"),full_page=True)
 page.set_viewport_size({"width":390,"height":844})
 assert page.evaluate("document.documentElement.scrollWidth <= innerWidth")
 page.locator("summary").first.click()
 expect(page.locator("details[open]").first).to_be_visible()
 page.screenshot(path=str(out/"catalog-mobile.png"),full_page=True)
 passed("Category, stock, price sorting and mobile filters work together")
 page.goto(base,wait_until="networkidle")
 page.locator("#store-search").fill("tetra")
 page.locator(".store-search > button[type=submit]").click()
 page.wait_for_url("**/urunler?q=tetra",timeout=60000)
 expect(page.locator("main h1:visible")).to_contain_text("tetra",timeout=60000)
 passed("Header search submits to real catalog results")
 page.keyboard.press("Control+k")
 expect(page.locator("dialog.store-search-modal[open]")).to_be_visible()
 page.get_by_label("Ürün veya rehber arayın").fill("akvaryum")
 page.wait_for_timeout(1200)
 page.keyboard.press("Tab")
 assert page.evaluate("document.querySelector('dialog[open]').contains(document.activeElement)")
 page.keyboard.press("Escape")
 expect(page.locator("dialog.store-search-modal")).to_have_count(0)
 passed("Keyboard search opens, searches, contains focus and closes")
 page.goto(base+"/urunler?q=zzzxxyydoesnotexist",wait_until="networkidle",timeout=60000)
 expect(page.get_by_text("Aramanızla eşleşen ürün bulunamadı")).to_be_visible()
 passed("Empty catalog results offer recovery")
 page.locator(".store-cart-button").click()
 page.locator("dialog.store-cart[open] .store-cart-remove").click()
 expect(page.locator(".store-cart-empty")).to_be_visible()
 passed("Removing final item shows empty cart")
 assert errors==[],errors
 passed("No browser runtime errors across tested routes")
 (out/"verification.json").write_text(json.dumps({"passed":results,"errors":errors},ensure_ascii=False,indent=2),encoding="utf-8")
 b.close()
